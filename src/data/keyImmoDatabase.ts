export function findBestKeyRecord(
  records: KeyProgrammingRecord[],
  make: string,
  model: string,
  year: number
): KeyProgrammingRecord | null {
  const mLower = make.trim().toLowerCase();
  const mdlLower = model.trim().toLowerCase();

  // Exact or substring model + year match first
  const exactYearMatch = records.find(
    (r) =>
      r.make.toLowerCase() === mLower &&
      year >= r.from &&
      year <= r.to &&
      (r.model.toLowerCase() === mdlLower ||
        r.model.toLowerCase().includes(mdlLower) ||
        mdlLower.includes(r.model.toLowerCase().split(' / ')[0]))
  );
  if (exactYearMatch) return exactYearMatch;

  // Brand + year match
  const makeYearMatch = records.find(
    (r) => r.make.toLowerCase() === mLower && year >= r.from && year <= r.to
  );
  if (makeYearMatch) return makeYearMatch;

  // Brand token match (e.g. Peugeot matches Peugeot / Citroën)
  const tokenMatch = records.find(
    (r) =>
      (r.make.toLowerCase().includes(mLower) || mLower.includes(r.make.toLowerCase().split(' / ')[0])) &&
      year >= r.from &&
      year <= r.to
  );
  if (tokenMatch) return tokenMatch;

  // Fallback any record for brand
  return (
    records.find(
      (r) => r.make.toLowerCase() === mLower || r.make.toLowerCase().includes(mLower)
    ) ?? null
  );
}
